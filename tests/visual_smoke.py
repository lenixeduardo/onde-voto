from playwright.sync_api import sync_playwright
from pathlib import Path
root=Path(__file__).parents[1]
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1440,'height':1080})
 errors=[]
 page.on('pageerror',lambda e: errors.append(str(e)))
 page.goto('http://127.0.0.1:3000/',wait_until='networkidle',timeout=20000)
 page.locator('.dynamic-result').wait_for(state='visible')
 print('initial',page.locator('.success-banner').inner_text(),page.locator('h1').inner_text())
 page.screenshot(path=str(root/'captura-integracao-desktop.png'),full_page=True)
 page.locator('summary').click()
 page.locator('#secao').fill('999')
 page.get_by_role('button',name='Buscar alteração').click()
 page.locator('#empty-card').wait_for(state='visible')
 assert 'não incluída' in page.locator('#empty-title').inner_text()
 print('exact section negative OK')
 page.locator('#secao').fill('123')
 page.get_by_role('button',name='Buscar alteração').click()
 page.locator('.dynamic-result').wait_for(state='visible')
 assert 'Irapuá' in page.locator('.dynamic-result').inner_text()
 print('exact section positive OK')
 page.select_option('#estado','AL')
 page.locator('#cidade').fill('Traipu')
 page.locator('#zona').fill('20')
 page.locator('#secao').fill('99')
 page.get_by_role('button',name='Buscar alteração').click()
 page.locator('.reported-banner').wait_for(state='visible')
 assert 'noticiada' in page.locator('.reported-banner').inner_text().lower()
 print('reported result status OK')
 page.select_option('#estado','SP')
 page.locator('#cidade').fill('São Paulo')
 page.locator('#zona').fill('345')
 page.locator('#secao').fill('')
 page.get_by_role('button',name='Buscar alteração').click()
 page.locator('#empty-card').wait_for(state='visible')
 assert 'não significa' in page.locator('#empty-card').inner_text().lower()
 print('uncovered zone notice OK')
 page.set_viewport_size({'width':390,'height':844})
 page.select_option('#estado','RJ')
 page.locator('#cidade').fill('Rio de Janeiro')
 page.locator('#zona').fill('188')
 page.get_by_role('button',name='Buscar alteração').click()
 page.locator('.dynamic-result').wait_for(state='visible')
 page.locator('details summary').click()
 page.screenshot(path=str(root/'captura-integracao-mobile.png'),full_page=True)
 print('mobile overflow',page.evaluate('document.documentElement.scrollWidth-window.innerWidth'))
 print('page errors',errors)
 browser.close()
